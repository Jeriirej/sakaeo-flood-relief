/**
 * ฟังก์ชันหาเบอร์เจ้าหน้าที่ในพื้นที่ของผู้ขอ SOS โดยค้นหาจากชื่ออำเภอหรือที่อยู่
 */
export function getLocalOfficialsForSos(sosItem) {
  if (!sosItem) return [];

  // หาอำเภอจากฟิลด์ district หรือตรวจคำใน address / landmark
  let matchedDistrict = sosItem.district;

  if (!matchedDistrict) {
    const fullText = `${sosItem.address || ''} ${sosItem.landmark || ''}`;
    for (const d of Object.keys(DISTRICT_LOCAL_CONTACTS)) {
      if (fullText.includes(d)) {
        matchedDistrict = d;
        break;
      }
    }
  }

  // ลบคำว่า "อำเภอ" หรือ "อ." ออกถ้ามี เพื่อค้นหาใน dictionary
  if (matchedDistrict) {
    matchedDistrict = matchedDistrict.replace(/อำเภอ|อ\./g, '').trim();
  }

  if (matchedDistrict && DISTRICT_LOCAL_CONTACTS[matchedDistrict]) {
    return {
      districtName: matchedDistrict,
      contacts: DISTRICT_LOCAL_CONTACTS[matchedDistrict].officials
    };
  }

  // หากไม่ระบุอำเภอ ให้ดึงเจ้าหน้าที่ศูนย์กลาง จ.สระแก้ว
  return {
    districtName: "จังหวัดสระแก้ว (ศูนย์กลาง)",
    contacts: DISTRICT_LOCAL_CONTACTS["เมืองสระแก้ว"].officials
  };
}

